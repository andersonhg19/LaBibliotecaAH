-- ============================================================================
-- V1 — Esquema de auth-service de La Biblioteca AH
-- ============================================================================
--
-- Es la foto FINAL del esquema de auth-service de Oh Churus (sus V1..V8)
-- consolidada en una sola migracion, sin lo que era de finanzas: el dia de
-- corte del presupuesto, la moneda y los decimales del usuario.
--
-- Decisiones que se heredan tal cual (ver Oh Churus, V3..V5):
--  · La cascada va en un solo sentido: borrar un usuario se lleva sus
--    asignaciones de rol; borrar un rol asignado lo impide la clave ajena.
--  · No existir es no poder: sin fila en bah_auth_role_permission, ese rol no
--    tiene nada en esa pagina.
--  · La auditoria guarda el correo del actor ademas de su id y no tiene clave
--    ajena hacia usuarios: borrar una cuenta no borra su rastro.
--
-- Sintaxis valida tal cual en PostgreSQL y en H2 (las pruebas montan el
-- esquema con estas mismas migraciones).
-- ============================================================================

CREATE TABLE bah_auth_user (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name       VARCHAR(100) NOT NULL,
    email      VARCHAR(150) NOT NULL UNIQUE,
    password   VARCHAR(255) NOT NULL,
    active     BOOLEAN      NOT NULL,
    created_at TIMESTAMP(6),
    updated_at TIMESTAMP(6),
    PRIMARY KEY (id),
    CONSTRAINT ck_usuario_correo_no_vacio CHECK (CHAR_LENGTH(TRIM(email)) > 0)
);

CREATE TABLE bah_auth_role (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name        VARCHAR(50)  NOT NULL UNIQUE,
    description VARCHAR(200),
    active      BOOLEAN      NOT NULL,
    created_at  TIMESTAMP(6),
    updated_at  TIMESTAMP(6),
    PRIMARY KEY (id),
    CONSTRAINT ck_rol_nombre_no_vacio CHECK (CHAR_LENGTH(TRIM(name)) > 0)
);

CREATE TABLE bah_auth_user_role (
    user_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_user_role_user FOREIGN KEY (user_id)
        REFERENCES bah_auth_user (id) ON DELETE CASCADE,
    CONSTRAINT fk_user_role_role FOREIGN KEY (role_id)
        REFERENCES bah_auth_role (id)
);

CREATE INDEX idx_user_role_role ON bah_auth_user_role (role_id);

CREATE TABLE bah_auth_module (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code       VARCHAR(50)  NOT NULL UNIQUE,
    name       VARCHAR(100) NOT NULL,
    icon       VARCHAR(50),
    sort_order INTEGER      NOT NULL,
    active     BOOLEAN      NOT NULL,
    created_at TIMESTAMP(6),
    updated_at TIMESTAMP(6),
    PRIMARY KEY (id)
);

CREATE TABLE bah_auth_page (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    module_id  BIGINT       NOT NULL,
    code       VARCHAR(50)  NOT NULL,
    name       VARCHAR(100) NOT NULL,
    route      VARCHAR(100) NOT NULL,
    icon       VARCHAR(50),
    in_menu    BOOLEAN      NOT NULL,
    sort_order INTEGER      NOT NULL,
    active     BOOLEAN      NOT NULL,
    created_at TIMESTAMP(6),
    updated_at TIMESTAMP(6),
    PRIMARY KEY (id),
    CONSTRAINT fk_pagina_modulo FOREIGN KEY (module_id) REFERENCES bah_auth_module (id),
    CONSTRAINT uk_pagina_modulo_codigo UNIQUE (module_id, code)
);

CREATE TABLE bah_auth_role_permission (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    role_id    BIGINT  NOT NULL,
    page_id    BIGINT  NOT NULL,
    can_read   BOOLEAN NOT NULL,
    can_create BOOLEAN NOT NULL,
    can_update BOOLEAN NOT NULL,
    can_delete BOOLEAN NOT NULL,
    active     BOOLEAN NOT NULL,
    created_at TIMESTAMP(6),
    updated_at TIMESTAMP(6),
    PRIMARY KEY (id),
    CONSTRAINT fk_permiso_rol FOREIGN KEY (role_id)
        REFERENCES bah_auth_role (id) ON DELETE CASCADE,
    CONSTRAINT fk_permiso_pagina FOREIGN KEY (page_id)
        REFERENCES bah_auth_page (id) ON DELETE CASCADE,
    CONSTRAINT uk_permiso_rol_pagina UNIQUE (role_id, page_id)
);

CREATE INDEX idx_permiso_rol ON bah_auth_role_permission (role_id);

CREATE TABLE bah_auth_audit_log (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    actor_user_id BIGINT,
    actor_email   VARCHAR(150),
    entity_type   VARCHAR(60)  NOT NULL,
    entity_id     BIGINT,
    action        VARCHAR(40)  NOT NULL,
    details       VARCHAR(1000),
    occurred_at   TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id)
);

CREATE INDEX idx_auditoria_actor ON bah_auth_audit_log (actor_user_id);
CREATE INDEX idx_auditoria_entidad ON bah_auth_audit_log (entity_type, entity_id);
CREATE INDEX idx_auditoria_fecha ON bah_auth_audit_log (occurred_at);

CREATE TABLE bah_auth_app_config (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    config_key   VARCHAR(80)  NOT NULL UNIQUE,
    config_value VARCHAR(300) NOT NULL,
    description  VARCHAR(300),
    active       BOOLEAN      NOT NULL,
    created_at   TIMESTAMP(6),
    updated_at   TIMESTAMP(6),
    PRIMARY KEY (id)
);
